/**
 * AI Explanation Panel.
 * Calls POST /api/ai/explain with actual model results.
 * The LLM explains outputs — it does NOT generate new scores.
 */
import React, { useState } from 'react';
import type { PatientContext, ShapValue } from '../../types';
import { explainPrediction } from '../../api/endpoints';
import { extractErrorMessage } from '../../api/client';
import { Spinner, ErrorBox, LLMTag, Disclaimer } from '../shared';

interface AIExplainPanelProps {
  patientContext: PatientContext;
  llmConfigured: boolean;
}

export function AIExplainPanel({ patientContext, llmConfigured }: AIExplainPanelProps) {
  const [explanation, setExplanation] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const handleExplain = async () => {
    if (loading) return;
    setLoading(true);
    setError(null);
    setExplanation(null);

    try {
      const shapValues: ShapValue[] = patientContext.sepsis_result?.shap_values ?? [];
      const resp = await explainPrediction({
        sepsis_result: patientContext.sepsis_result
          ? { ...patientContext.sepsis_result, shap_values: undefined }
          : undefined,
        organ_results: patientContext.organ_results?.map(o => ({
          organ: o.organ,
          probability: o.probability,
          label: o.label,
          risk_level: o.risk_level,
        })),
        antibiotic_result: patientContext.antibiotic_result
          ? {
              predicted_class: patientContext.antibiotic_result.predicted_class,
              data_disclaimer: patientContext.antibiotic_result.data_disclaimer,
            }
          : undefined,
        shap_values: shapValues.slice(0, 8),
      });
      setExplanation(resp.explanation);
    } catch (err) {
      setError(extractErrorMessage(err));
    } finally {
      setLoading(false);
    }
  };

  if (!llmConfigured) {
    return (
      <div className="error-box">
        Groq LLM not configured. Set <code>GROQ_API_KEY</code> in <code>backend/.env</code>.
      </div>
    );
  }

  const hasContext =
    patientContext.sepsis_result ||
    (patientContext.organ_results?.length ?? 0) > 0 ||
    patientContext.antibiotic_result;

  return (
    <div>
      <Disclaimer text="This explanation is generated by Groq LLM based on model outputs. It is not a clinical opinion." />

      {!hasContext && (
        <p style={{ color: 'var(--color-text-muted)', fontSize: '0.875rem', marginBottom: '1rem' }}>
          Run a prediction first, then click Explain to generate an AI explanation.
        </p>
      )}

      <button
        className="btn btn-primary"
        onClick={handleExplain}
        disabled={loading || !hasContext}
      >
        {loading ? <><Spinner size={16} /> Generating Explanation…</> : '✨ Explain Prediction'}
      </button>

      {error && <div style={{ marginTop: '1rem' }}><ErrorBox message={error} onRetry={handleExplain} /></div>}

      {explanation && (
        <div style={{ marginTop: '1.25rem' }}>
          <div style={{ marginBottom: '0.5rem', display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
            <LLMTag />
            <span style={{ fontSize: '0.8rem', color: 'var(--color-text-muted)' }}>Groq LLM explanation</span>
          </div>
          <div
            style={{
              background: 'var(--color-surface-2)',
              borderRadius: '8px',
              padding: '1rem',
              whiteSpace: 'pre-wrap',
              fontSize: '0.9rem',
              lineHeight: 1.6,
              border: '1px solid var(--color-border)',
            }}
          >
            {explanation}
          </div>
        </div>
      )}
    </div>
  );
}
